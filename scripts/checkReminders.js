const assert = require('assert');
const { createReminder, evaluateReminder, jobHasEnded, nextReminderDelay } = require('../out/reminders');
const start = 1000000;
const make = extra => createReminder({ mode: 'available', server: 'node', gpuIds: ['GPU-a','GPU-b'], ...extra }, start);
const sample = free => ({ online: true, fresh: true, availableIds: free, knownGpuIds: ['GPU-a','GPU-b'] });
let watch = make({ expiresAt: start + 600000 });
assert.strictEqual(evaluateReminder(watch, sample(['GPU-a']), start + 1), undefined);
assert.strictEqual(evaluateReminder(watch, sample(['GPU-a','GPU-b']), start + 2), undefined);
assert.strictEqual(evaluateReminder(watch, sample(['GPU-a','GPU-b']), start + 30002), 'fire');
watch = make();
evaluateReminder(watch, sample(['GPU-a','GPU-b']), start + 1);
assert.strictEqual(evaluateReminder(watch, { ...sample([]), online: false }, start + 30001), undefined);
assert.strictEqual(evaluateReminder(watch, sample(['GPU-a','GPU-b']), start + 60001), undefined, 'An offline gap must break stable-free evidence.');
assert.strictEqual(evaluateReminder(make({ expiresAt: start + 10 }), sample([]), start + 20), 'expire');
assert.strictEqual(evaluateReminder(createReminder({ mode:'at',server:'node',at:start+1000 },start), sample([]),start+1001),'fire');
assert.throws(() => make({ gpuIds:[] }), /GPU/);
assert.throws(() => createReminder({mode:'taskEnded',server:'node',pid:'4'},start), /identity/);
const task = createReminder({mode:'taskEnded',server:'node',pid:'4',identity:'boot:12'},start);
assert.strictEqual(evaluateReminder(task,{online:true,fresh:true,taskIdentity:'boot:12'},start+1),undefined);
assert.strictEqual(evaluateReminder(task,{online:true,fresh:true,taskIdentity:'boot:99'},start+2),'fire', 'Reused PID belongs to a different task.');
assert.strictEqual(jobHasEnded('12','JobState=RUNNING','12|RUNNING|0:0\n12.batch|FAILED|1:0'),false,'A failed step cannot mark a still-running job as ended.');
assert.strictEqual(jobHasEnded('12',null,'12|OUT_OF_MEMORY|0:9'),true);
const far=createReminder({mode:'at',server:'node',at:start+29*86400000,expiresAt:start+30*86400000},start);
assert.ok(nextReminderDelay([far],start)<=86400000,'Far-future timers must not overflow Node setTimeout.');
console.log('Stable GPU availability, task identity, reminder deadlines and scheduled checks passed.');
